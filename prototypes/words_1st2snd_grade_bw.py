@contextmanager
def db_cursor():
    conn = dbpool.getconn()
    try:
        with conn.cursor() as cur:
            yield cur
            conn.commit()
    except:
        conn.rollback()
        raise
    finally:
        dbpool.putconn(conn)

# create wikipedia word frequency dictionary
# get raw list from https://github.com/adno/wikipedia-word-frequency-clean/blob/main/results/dewiki-frequency-20221020.tsv.xz
frequencies = {}

with open('dewiki-frequency-20221020.tsv', 'r', encoding='utf-8') as frequency_file:
    #skip the header line
    next(frequency_file)
    for line in frequency_file:
        parts = line.strip().split('\t')
        if len(parts) < 2:
            continue
        word = parts[0]
        frequency = int(parts[1])
        if word in frequencies:
            raise ValueError(f"Duplicate word found: {word}")
        frequencies[word] = frequency

